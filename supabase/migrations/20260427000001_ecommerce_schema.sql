create policy shipments_select_authenticated on public.shipments
  for select to authenticated using (true);
create policy events_select_authenticated on public.events
  for select to authenticated using (true);
create policy targets_select_authenticated on public.targets
  for select to authenticated using (true);
create policy calendar_events_select_authenticated on public.calendar_events
  for select to authenticated using (true);
